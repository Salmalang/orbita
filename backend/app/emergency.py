class PackError(Exception):
    def __init__(self, msg: str, code: int = 403):
        super().__init__(msg)
        self.code = code


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _iso(d: datetime) -> str:
    return d.isoformat(timespec="seconds")


# ============================================================================ access tokens
class PackService:
    """Issues, validates and revokes incident-bound responder links."""

    def __init__(self, store, ttl_min: int | None = None, secret: str | None = None):
        self.store = store
        self.ttl = timedelta(minutes=ttl_min or DEFAULT_TTL_MIN)
        self._fixed = secret or os.environ.get("ARGOS_PACK_SECRET")

    @property
    def _secret(self) -> bytes:
        # read on every use: a demo reset clears the store, and a cached copy would then disagree after a restart
        return (self._fixed or self._stored_secret()).encode()

    def _stored_secret(self) -> str:
        meta = self.store.get_record("meta", "pack_secret")
        if not meta:
            meta = {"id": "pack_secret", "secret": secrets.token_hex(32)}
            self.store.put_record("meta", meta)
        return meta["secret"]

    @staticmethod
    def eligible(case: dict) -> tuple[bool, str]:
        if case.get("kind") != "SENSOR_ALERT":
            return False, "Only fire-related sensor incidents get a firefighter pack (drone patrol findings do not)."
        if case.get("severity") != "CRITICAL" and not case.get("escalations"):
            return False, "Available when a fire-related incident reaches CRITICAL severity."
        return True, "Fire-related incident at CRITICAL severity."

    def _sign(self, case_id: str, jti: str, exp: int) -> str:
        return hmac.new(self._secret, f"{case_id}|{jti}|{exp}".encode(), hashlib.sha256).hexdigest()[:32]

    def get(self, case_id: str) -> dict | None:
        return self.store.get_record("emergency_pack", case_id)

    def state(self, rec: dict | None, now: datetime | None = None) -> str:
        if not rec:
            return "NONE"
        if rec.get("revoked"):
            return "REVOKED"
        return "EXPIRED" if (now or _now()).timestamp() >= rec["exp"] else "ACTIVE"

    def issue(self, case: dict, actor: str = "system", auto: bool = False) -> dict:
        ok, why = self.eligible(case)
        if not ok:
            raise PackError(why, 409)
        now = _now()
        exp = int((now + self.ttl).timestamp())
        jti = secrets.token_urlsafe(12)
        token = f"{jti}.{exp}.{self._sign(case['id'], jti, exp)}"
        prev = self.get(case["id"])
        rec = {"id": case["id"], "token": token, "jti": jti, "exp": exp, "issued_at": _iso(now),
               "expires_at": _iso(datetime.fromtimestamp(exp, timezone.utc)), "revoked": False, "auto": auto,
               "issued_by": actor, "generation": (prev or {}).get("generation", 0) + 1, "opened": None}
        self.store.put_record("emergency_pack", rec)
        # the token itself never enters the event chain (or Hedera): only its expiry and a digest
        self.store.append("emergency_pack_issued", "system" if auto else "human",
                          {"expires_at": rec["expires_at"], "generation": rec["generation"], "auto": auto,
                           "token_sha256": hashlib.sha256(token.encode()).hexdigest(), "demo_access": True},
                          actor=actor, case_id=case["id"])
        return rec

    def ensure(self, case: dict) -> dict | None:
        """Automatic issue for an eligible incident that has no usable link yet."""
        if not self.eligible(case)[0]:
            return None
        rec = self.get(case["id"])
        if self.state(rec) == "ACTIVE" or (rec and rec.get("revoked")):
            return rec
        return self.issue(case, actor="system", auto=True)

    def revoke(self, case_id: str, actor: str = "operator") -> dict:
        rec = self.get(case_id)
        if not rec:
            raise PackError("No firefighter pack was issued for this incident.", 404)
        rec["revoked"] = True
        rec["revoked_at"] = _iso(_now())
        self.store.put_record("emergency_pack", rec)
        self.store.append("emergency_pack_revoked", "human", {"generation": rec["generation"]}, actor=actor, case_id=case_id)
        return rec

    def validate(self, case_id: str, token: str | None) -> dict:
        if not token:
            raise PackError("Access token missing. Scan the QR code from the ARGOS incident page.", 401)
        try:
            jti, exp_s, sig = token.split(".")
            exp = int(exp_s)
        except ValueError:
            raise PackError("Invalid access link.", 401)
        if not hmac.compare_digest(sig, self._sign(case_id, jti, exp)):
            raise PackError("Invalid access link.", 401)
        rec = self.get(case_id)
        if not rec or not hmac.compare_digest(rec["jti"], jti):
            raise PackError("This link has been replaced by a newer one. Scan the current QR code.", 403)
        if rec.get("revoked"):
            raise PackError("This link was revoked by the control room.", 403)
        if _now().timestamp() >= exp:
            raise PackError("This link has expired. Ask the control room for a new QR code.", 410)
        if not rec.get("opened"):
            rec["opened"] = _iso(_now())
            self.store.put_record("emergency_pack", rec)
            self.store.append("emergency_pack_opened", "system", {"generation": rec["generation"]}, case_id=case_id)
        return rec


# ============================================================================ geometry helpers
def hall_to_site(x: float, y: float) -> tuple[float, float]:
    o = SITE["hall"]["offset"]
    return round(o["x"] + x, 2), round(o["y"] + y, 2)


def _dist(a, b) -> float:
    return math.hypot(a[0] - b[0], a[1] - b[1])


def _r(v, nd):
    if v is None:
        return None
    return int(round(float(v))) if nd == 0 else round(float(v), nd)


def _trend(before, now) -> str:
    if before is None or now is None:
        return "unknown"
    if abs(now - before) <= max(0.1 * abs(before), 1e-6):
        return "stable"
    return "rising" if now > before else "falling"


# ============================================================================ briefing
def build_briefing(case: dict, *, facility: dict, events: list[dict], live: dict | None = None,
                   recent_ticks: list[dict] | None = None, missions: list[dict] | None = None,
                   findings: list[dict] | None = None, chain: dict | None = None, hedera: dict | None = None,
                   model_metrics: dict | None = None, contacts: list[dict] | None = None, now: datetime | None = None) -> dict:
    """Assemble the responder briefing from ARGOS records only. `live` is the replay's latest state, passed
    only when the replay currently playing is the one that produced this incident."""
    now = now or _now()
    nodes_by_id = {n["id"]: n for n in facility["nodes"]}
    ev_nodes = (case.get("evidence") or {}).get("nodes") or {}
    fire_nodes = list(case.get("fire_nodes") or [])
    live_nodes = (live or {}).get("nodes") or {}
    live_dec = (live or {}).get("decision") or {}

    # ---------------------------------------------------------------- sensor observations (recorded values only)
    obs = []
    order = sorted(ev_nodes, key=lambda k: -(ev_nodes[k].get("p_fire") or 0))
    for nid in order:
        v, meta = ev_nodes[nid], nodes_by_id.get(nid, {"label": nid, "x": None, "y": None})
        if nid not in fire_nodes and (v.get("p_fire") or 0) < 0.5:
            continue
        cur = live_nodes.get(nid)
        readings = []
        for k, (lab, unit, nd) in READING_LABEL.items():
            a = v.get("readings", {}).get(k)
            b = (cur or {}).get("readings", {}).get(k) if cur else None
            readings.append({"key": k, "label": lab, "unit": unit, "at_detection": _r(a, nd), "now": _r(b, nd),
                             "trend": _trend(a, b) if cur else "unknown"})
        site_xy = hall_to_site(meta["x"], meta["y"]) if meta.get("x") is not None else None
        obs.append({"node": nid, "label": meta["label"], "site_xy": site_xy, "fire_signal": nid in fire_nodes,
                    "p_fire_at_detection": _r(v.get("p_fire"), 3), "p_fire_now": _r((cur or {}).get("p_fire"), 3) if cur else None,
                    "readings": readings, "last_seen": (cur or {}).get("last_seen")})

    # ---------------------------------------------------------------- incident location (sensor-based estimate)
    pts = [hall_to_site(nodes_by_id[n]["x"], nodes_by_id[n]["y"]) for n in fire_nodes if n in nodes_by_id]
    location = None
    if pts:
        cx, cy = sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts)
        radius = max([_dist((cx, cy), p) for p in pts] + [0]) + 3.0
        labels = [nodes_by_id[n]["label"] for n in fire_nodes if n in nodes_by_id]
        location = {"x": round(cx, 2), "y": round(cy, 2), "r": round(radius, 2), "nodes": labels,
                    "room": "Production Hall A",
                    "text": f"Production Hall A, area around sensors {', '.join(labels)} (where the fire signal was measured)",
                    "basis": "Sensor-based estimate from the positions of the sensors that measured the fire signal. "
                             "Not a confirmed fire origin."}

    # ---------------------------------------------------------------- confirmed facts (recorded by ARGOS or people)
    facts = [{"text": f"ARGOS opened incident {case['id']} at {LEVEL_TEXT.get(case['severity'], case['severity'])} severity.",
              "source": "ARGOS record", "ts": case.get("opened_wall_ts")}]
    if case.get("escalations"):
        facts.append({"text": f"Fire signal still present or returned after the intervention ({case['escalations']} time(s)).",
                      "source": "ARGOS record", "ts": None})
    actions = []
    if case.get("action"):
        actions.append({"role": "Technician", "text": case["action"]["text"], "ts": case["action"].get("wall_ts")})
        facts.append({"text": "A technician recorded an intervention (see actions).", "source": "Technician", "ts": case["action"].get("wall_ts")})
    if case.get("verification"):
        ver = case["verification"]
        actions.append({"role": "Independent verifier", "text": ("Approved: " if ver.get("approved") else "Rejected: ") + (ver.get("note") or "-"),
                        "ts": ver.get("wall_ts")})
    if case.get("outcome"):
        facts.append({"text": f"Real outcome confirmed by a second person: {case['outcome'].get('text') or case['outcome']['label']}.",
                      "source": "Verifier", "ts": case["outcome"].get("wall_ts")})
    if case.get("stabilization"):
        st = case["stabilization"]
        facts.append({"text": ("Recovery confirmed on live readings." if st.get("passed")
                               else f"Recovery NOT confirmed ({st.get('measured_minutes', 0)} of {st.get('required_minutes', 15)} min of live normal readings)."),
                      "source": "ARGOS measurement", "ts": st.get("checked_at")})

    # ---------------------------------------------------------------- AI assessment and uncertainty
    reasons = case.get("findings") or []
    p_det = [o["p_fire_at_detection"] for o in obs if o["p_fire_at_detection"] is not None]
    ne = (model_metrics or {}).get("nested_estimate") or {}
    uncertainty = ["The AI fire likelihood is a model score learned from recorded experiments, not a calibrated probability."]
    if ne:
        uncertainty.append(f"Held-out test on 32 recorded events: {ne.get('fires_detected')}/{ne.get('fire_events')} fires detected, "
                           f"{ne.get('nuisance_false_alarms')}/{ne.get('nuisance_events')} nuisance events (e.g. welding fumes) raised false alarms.")
    uncertainty.append("Tested on staged experiments in one hall, not in a real factory fire. Sensors cover only Hall A.")
    trend_p = None
    if recent_ticks:
        vals = [t.get("max_p_fire") for t in recent_ticks if t.get("max_p_fire") is not None]
        if len(vals) >= 2:
            trend_p = {"from": _r(vals[0], 3), "to": _r(vals[-1], 3), "trend": _trend(vals[0], vals[-1]),
                       "window": f"{recent_ticks[0]['t']} to {recent_ticks[-1]['t']}"}
    ai = {"model": (case.get("evidence") or {}).get("model"), "level_at_detection": case.get("severity"),
          "reasons": reasons, "fire_signal_sensors": [o["label"] for o in obs if o["fire_signal"]],
          "max_p_fire_at_detection": max(p_det) if p_det else None, "p_fire_trend": trend_p, "uncertainty": uncertainty}

    # ---------------------------------------------------------------- hypotheses (only with evidence)
    hyps = []
    if location:
        hyps.append({"text": f"Fire most likely near sensors {', '.join(location['nodes'])} in Production Hall A.",
                     "basis": "Sensors with the strongest fire signal (AI model + CO/particle readings)."})
        near = [c for c in facility.get("checkpoints", []) if set(c.get("near_nodes", [])) & set(fire_nodes)
                and "exit" not in c["label"].lower()]
        if near:
            hyps.append({"text": "Equipment located near those sensors (demonstration layout): " + ", ".join(c["label"] for c in near) + ".",
                         "basis": "Proximity on the layout only. ARGOS has not determined the cause."})
    unknowns = ["Fire origin and cause: not determined.",
                "People inside the building: ARGOS has no headcount.",
                "Fire spread or smoke outside Hall A: no sensors there.",
                "Structural condition and visibility inside: unknown to ARGOS."]
    if not live:
        unknowns.insert(0, "Current readings: the recording that produced this incident is not playing now, so only readings at detection are shown.")

    # ---------------------------------------------------------------- drone (simulated)
    drone = {"simulated": True, "note": "Simulated drone: no physical drone, camera or thermal model. Results are entered by the operator.",
             "missions": [{"id": m["id"], "mode": m.get("mode"), "status": m.get("status"),
                           "checkpoints": [{"label": c["label"], "status": c.get("status"), "result": c.get("result")} for c in m.get("checkpoints", [])]}
                          for m in (missions or [])],
             "findings": [{"id": f["id"], "type": f.get("type_label"), "checkpoint": f.get("checkpoint_label"),
                           "severity": f.get("severity"), "note": f.get("note"), "illustrative": True} for f in (findings or [])]}

    # ---------------------------------------------------------------- access & hazards
    cps = {c["id"]: c for c in facility.get("checkpoints", [])}
    blocked = list(SITE.get("blocked_passages", []))
    for f in findings or []:
        if f.get("type") in ("obstructed_exit", "blocked_passage") and not f.get("resolved"):
            cp = cps.get(f.get("checkpoint"))
            if cp:
                x, y = hall_to_site(cp["x"], cp["y"])
                blocked.append({"id": f["id"], "label": f"{f.get('type_label', 'Obstruction')} at {cp['label']}", "x": x, "y": y,
                                "source": "Reported by a simulated drone patrol (illustrative)", "exit": SITE["hall_checkpoint_exits"].get(cp["id"])})
    hazards = []
    for h in SITE["hazards"]:
        d = _dist((location["x"], location["y"]), (h["x"], h["y"])) if location else None
        hazards.append({**h, "distance_m": _r(d, 0), "near_incident": d is not None and d <= 15})
    hazards.sort(key=lambda h: (h["distance_m"] is None, h["distance_m"] or 0))
    access = {"firefighter_access": SITE["firefighter_access"], "exits": SITE["exits"], "blocked": blocked, "hazards": hazards,
              "power_isolation": SITE["power_isolation"], "extinguishers": SITE["extinguishers"], "hydrants": SITE["hydrants"],
              "assembly_points": SITE["assembly_points"], "safety_notes": SITE["safety_notes"],
              "contacts": contacts or [], "demo": True,
              "route_note": "No route is recommended. Route suitability and building entry are decided by authorized emergency responders."}

    # ---------------------------------------------------------------- verification
    case_events = [e for e in events if e.get("case_id") == case["id"]]
    last_case_seq = max((e["seq"] for e in case_events), default=None)
    hv = None
    if hedera:
        latest = hedera.get("latest") or {}
        through = (latest.get("snapshot") or {}).get("last_seq")
        st = (latest.get("verification") or {}).get("status") or latest.get("status") or "NOT_ANCHORED"
        hv = {"status": st if latest else "NOT_ANCHORED", "anchored_through_event": through,
              "covers_this_incident": bool(through and last_case_seq and through >= last_case_seq),
              "topic_id": latest.get("topic_id"), "transaction_id": latest.get("transaction_id"),
              "consensus_timestamp": latest.get("consensus_timestamp"), "explorer": hedera.get("explorer")}
    verification = {"local_chain_ok": (chain or {}).get("ok"), "chain_events": (chain or {}).get("events"),
                    "incident_events": len(case_events), "hedera": hv,
                    "note": "Local SHA-256 event chain; Hedera holds only fingerprints, never this briefing or the layout."}

    timeline = [{"ts": e.get("wall_ts"), "data_ts": e.get("data_ts"), "kind": e["kind"],
                 "title": EVENT_TEXT.get(e["kind"], e["kind"].replace("_", " ").capitalize()), "source": e.get("source")}
                for e in case_events]
    last_wall = max([e.get("wall_ts") or "" for e in case_events] + [case.get("opened_wall_ts") or ""])

    return {
        "schema": SCHEMA, "demo": True, "demo_note": SITE["demo_note"], "not_a_plan": NOT_A_PLAN, "network_note": NETWORK_NOTE,
        "generated_at": _iso(now),
        "incident": {"id": case["id"], "severity": case["severity"], "severity_text": LEVEL_TEXT.get(case["severity"], case["severity"]),
                     "status": case["status"], "status_text": STATUS_TEXT.get(case["status"], case["status"]),
                     "zone": case.get("zone"), "zone_name": facility.get("name"), "site_name": SITE["name"],
                     "detected_recorded_ts": case.get("opened_data_ts"), "opened_wall_ts": case.get("opened_wall_ts"),
                     "replay_event": case.get("replay_event"), "historical_replay": True, "escalations": case.get("escalations", 0),
                     "last_update_wall": last_wall or None,
                     "last_data_ts": (live or {}).get("t"), "location": location},
        "live": {"available": bool(live), "level": live_dec.get("level"), "level_text": LEVEL_TEXT.get(live_dec.get("level"), None),
                 "data_ts": (live or {}).get("t"), "reasons": live_dec.get("reasons", [])},
        "confirmed_facts": facts, "sensor_observations": obs, "ai_assessment": ai, "hypotheses": hyps, "unknowns": unknowns,
        "actions": actions, "drone": drone, "access": access, "verification": verification, "timeline": timeline,
        "map": {"site": {k: SITE[k] for k in ("name", "size_m", "rooms", "hall_features", "exits", "firefighter_access", "power_isolation",
                                              "extinguishers", "hydrants", "hazards", "assembly_points")},
                "sensors": [{"label": n["label"], "x": hall_to_site(n["x"], n["y"])[0], "y": hall_to_site(n["x"], n["y"])[1],
                             "fire": n["id"] in fire_nodes} for n in facility["nodes"]],
                "incident": location, "blocked": blocked},
    }


# ============================================================================ QR code
def qr_png(url: str, scale: int = 10) -> bytes:
    import segno
    buf = io.BytesIO()
    segno.make(url, error="m").save(buf, kind="png", scale=scale, border=4, dark="#292A29", light="#FFFFFF")
    return buf.getvalue()


def qr_matrix(url: str):
    import segno
    return [list(r) for r in segno.make(url, error="m").matrix]


