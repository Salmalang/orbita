def draw_floor_plan(ax, b: dict, compact: bool = False) -> None:
    """Matplotlib rendering of the same plan the mobile page draws in SVG."""
    from matplotlib.patches import Circle, FancyBboxPatch, Polygon, Rectangle
    m, s = b["map"], b["map"]["site"]
    W, H = s["size_m"]["width"], s["size_m"]["height"]
    ax.set_xlim(-1, W + 1)
    ax.set_ylim(H + 1, -1)
    ax.set_aspect("equal")
    ax.axis("off")
    ax.add_patch(Rectangle((0, 0), W, H, fill=False, ec=C["line"], lw=0.8, ls=(0, (4, 3))))
    fs = 5.2 if compact else 6.5
    for r in s["rooms"]:
        hatch = "////" if r["type"] == "hazard" else None
        ax.add_patch(Rectangle((r["x"], r["y"]), r["w"], r["h"], fc=ROOM_FILL.get(r["type"], "#FFF"), ec=C["ink"] if r["type"] != "outdoor" else C["line"],
                               lw=1.4 if r["id"] == "HALL-A" else 0.9, hatch=hatch, ls="-" if r["type"] != "outdoor" else (0, (3, 2))))
        ty = r["y"] - 0.8 if r.get("label_above") else r["y"] + r["h"] / 2
        label = r["label"] if r["w"] >= 9 or len(r["label"]) < 14 else r["label"].replace(" ", "\n", 1)
        ax.text(r["x"] + r["w"] / 2, ty, label, ha="center", va="center", fontsize=fs, color=C["ink"], weight="bold", linespacing=1.0)
        if r.get("sub") and (r["h"] >= 5 or r.get("label_above")):
            ax.text(r["x"] + r["w"] / 2, ty - 1.1 if r.get("label_above") else ty + 1.1, r["sub"], ha="center", va="center", fontsize=fs - 1, color=C["muted"])
    for f in s["hall_features"]:
        ax.add_patch(Rectangle((f["x"], f["y"]), f["w"], f["h"], fc=ROOM_FILL.get(f["type"], "#EEE"), ec=C["taupe"], lw=0.6,
                               hatch="xx" if f["type"] == "hazard" else None, alpha=0.9))
