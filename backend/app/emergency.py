class _Pdf:
    """Very small flowing-text layout on A4 pages using matplotlib."""
    W_IN, H_IN, M = 8.27, 11.69, 0.55

    def __init__(self, pdf, b):
        self.pdf, self.b, self.fig, self.y, self.page = pdf, b, None, 0, 0
        self.new_page()

    def new_page(self):
        from matplotlib.figure import Figure
        if self.fig is not None:
            self._footer()
            self.pdf.savefig(self.fig)
        self.fig = Figure(figsize=(self.W_IN, self.H_IN))
        self.fig.patch.set_facecolor("white")
        self.page += 1
        self.y = self.M

    def _footer(self):
        b = self.b
        self.fig.text(self.M / self.W_IN, 0.3 / self.H_IN,
                      f"ARGOS · Firefighter briefing {b['incident']['id']} · generated {b['generated_at']} UTC · page {self.page} · "
                      "DEMO DATA: fictional factory layout", fontsize=6.5, color=C["muted"])

    def _fy(self, y_in):
        return 1 - y_in / self.H_IN

    def need(self, h_in):
        if self.y + h_in > self.H_IN - 0.6:
            self.new_page()

    def text(self, s, size=9, color=None, weight="normal", indent=0.0, width=None, gap=0.04, wrap_chars=None):
        wrap = wrap_chars or int(((width or (self.W_IN - 2 * self.M - indent)) * 72) / (size * (0.62 if weight == "bold" else 0.55)))
        lines = []
        for para in str(s).split("\n"):
            lines += textwrap.wrap(para, wrap) or [""]
        lh = size * 1.32 / 72
        for ln in lines:
            self.need(lh)
            self.fig.text((self.M + indent) / self.W_IN, self._fy(self.y), ln, fontsize=size, color=color or C["ink"], weight=weight, va="top")
            self.y += lh
        self.y += gap

    def heading(self, s):
        self.need(0.5)
        self.y += 0.08
        self.fig.text(self.M / self.W_IN, self._fy(self.y), s.upper(), fontsize=9.5, weight="bold", color=C["brown"], va="top")
        self.y += 0.2
        self.fig.add_artist(_hline(self.fig, self._fy(self.y), self.M / self.W_IN, 1 - self.M / self.W_IN))
        self.y += 0.07

    def box(self, s, fg, bg, size=8.5, weight="normal"):
        wrap = int(((self.W_IN - 2 * self.M - 0.3) * 72) / (size * (0.62 if weight == "bold" else 0.55)))
        lines = []
        for para in s.split("\n"):
            lines += textwrap.wrap(para, wrap) or [""]
        h = len(lines) * size * 1.32 / 72 + 0.18
        self.need(h)
        from matplotlib.patches import FancyBboxPatch
        self.fig.add_artist(FancyBboxPatch((self.M / self.W_IN, self._fy(self.y + h)), (self.W_IN - 2 * self.M) / self.W_IN, h / self.H_IN,
                                           boxstyle="round,pad=0,rounding_size=0.004", transform=self.fig.transFigure, fc=bg, ec=fg, lw=0.8))
        self.y += 0.09
        for ln in lines:
            self.fig.text((self.M + 0.15) / self.W_IN, self._fy(self.y), ln, fontsize=size, color=fg, weight=weight, va="top")
            self.y += size * 1.32 / 72
        self.y += 0.15

    def finish(self):
        self._footer()
        self.pdf.savefig(self.fig)


def _hline(fig, y, x0, x1):
    from matplotlib.lines import Line2D
    return Line2D([x0, x1], [y, y], transform=fig.transFigure, color=C["line"], lw=0.8)


def _fmt(ts):
    if not ts:
        return "-"
    return str(ts).replace("T", " ").replace("+00:00", " UTC")[:23]


