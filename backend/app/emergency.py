"""Firefighter Emergency Pack: incident-specific QR link, responder briefing and printable PDF.

* The QR code carries only a URL. The URL holds an opaque, signed, expiring and revocable token bound
  to one incident; the briefing itself is served by the ARGOS server after the token is checked.
* The facility layout is a FICTIONAL demonstration factory (data/emergency_site.json). Sensor readings,
  AI outputs, case events and drone records come from the real ARGOS incident; nothing is invented here.
* The briefing separates confirmed facts, sensor observations, AI hypotheses and unknowns. It never
  recommends an entry route: that decision belongs to the authorized incident commander.
"""
